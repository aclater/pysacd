#!/usr/bin/env python3
"""Generate docs/README.md (the documentation index) and each document's navigation header.

    python3 tools/docs_index.py           # rewrite the index and the headers
    python3 tools/docs_index.py --check   # exit 1 if anything is out of date (run by the tests)

The index lists every document with links to its sections. Each document starts with a
breadcrumb back to the README and the index and, when it has three or more sections, a
contents line. Both are generated from the headings, so they can't drift.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"

# Reading order. A document missing from here fails the check, so new docs get placed.
GROUPS: list[tuple[str, list[tuple[str, str]]]] = [
    ("Install", [
        ("install/README.md", "wheels, checking a download, building from source"),
    ]),
    ("Use", [
        ("user-guide.md", "a tour of the commands, and troubleshooting"),
        ("sacd_extract.md", "migrating from sacd_extract, compatibility policy, verification"),
        ("converting.md", "naming templates, tags, MusicBrainz, gapless PCM"),
        ("logging.md", "what to attach when something fails"),
    ]),
    ("Reference", [
        ("api.md", "the Python API, what's parsed, image formats"),
        ("ps3-protocol.md", "reading from a PS3: usage, the wire protocol and the PS3's quirks"),
        ("security.md", "hostile discs, servers and text"),
        ("performance.md", "benchmarks and their conditions"),
    ]),
    ("Internals", [
        ("development.md", "building, tests, CI, testing without a PS3, releases"),
        ("release-test-plan.md", "what every release is tested with, and its sign-off"),
    ]),
    ("Project", [
        ("why-pysacd.md", "what pysacd brings, and a first Python example"),
        ("author.md", "why pysacd exists, in the author's words"),
        ("clean-room.md", "where the code came from, licences, acknowledgements"),
    ]),
]

# Release steps live in development.md (existing repos may keep them there if the index links them
# under "Release"). Each entry is (link text, document, heading), checked against the document.
RELEASE: list[tuple[str, str, str]] = [
    ("Packaging and releases: the steps from version bump to tag, attestations and publishing",
     "development.md", "Packaging and releases"),
    ("Security releases: fixes to released code", "development.md", "Security releases"),
    ("Release test plan: every check a release runs, and its sign-off table", "release-test-plan.md",
     "How to use this plan"),
]

NAV_START, NAV_END = "<!-- nav: generated by tools/docs_index.py -->", "<!-- /nav -->"
MIN_SECTIONS = 3
FOOTER = "Part of the [DSD Toolbox](https://github.com/aclater/dsd-toolbox)."


def anchor(heading: str, seen: dict[str, int]) -> str:
    """GitHub's heading anchor: lower case, punctuation dropped, spaces to hyphens, -N for repeats."""
    text = re.sub(r"`|\*\*|\[([^\]]*)\]\([^)]*\)", r"\1", heading).strip().lower()
    slug = re.sub(r"[^\w\- ]", "", text).replace(" ", "-")
    n = seen.get(slug, 0)
    seen[slug] = n + 1
    return slug if n == 0 else f"{slug}-{n}"


def headings(text: str) -> tuple[str, list[tuple[str, str]]]:
    """The document's title and its level-2 sections as (text, anchor); fenced code is skipped."""
    title, fenced = "", False
    sections: list[tuple[str, str]] = []
    seen: dict[str, int] = {}
    for line in text.splitlines():
        if line.startswith("```"):
            fenced = not fenced
            continue
        m = None if fenced else re.match(r"(#{1,6}) (.+?)\s*$", line)
        if not m:
            continue
        a = anchor(m[2], seen)
        if len(m[1]) == 1 and not title:
            title = m[2]
        elif len(m[1]) == 2 and m[2] != "See also":   # the closing links aren't a section to list
            sections.append((m[2], a))
    return title, sections


def strip_nav(text: str) -> str:
    return re.sub(rf"\A{re.escape(NAV_START)}.*?{re.escape(NAV_END)}\n\n", "", text, flags=re.DOTALL)


def with_nav(text: str, name: str = "") -> str:
    """The navigation header for docs/<name>; a page in a subfolder links one level further up."""
    body = strip_nav(text)
    title, sections = headings(body)
    up = "../" * name.count("/")
    lines = [NAV_START, f"[pysacd]({up}../README.md) › [Documentation]({up}README.md) › {title}"]
    if len(sections) >= MIN_SECTIONS:
        lines += ["", "**Contents:** " + " · ".join(f"[{s}](#{a})" for s, a in sections)]
    return "\n".join(lines + [NAV_END, "", body])


def index() -> str:
    out = ["[pysacd](../README.md) › Documentation", "",
           '<img src="assets/icon-256.png" alt="" width="96">', "", "# Documentation", "",
           ("Every document about pysacd, grouped by what it is for. Start with the "
           "[README](../README.md) for what pysacd is."), ""]
    for group, docs in GROUPS:
        out += [f"## {group}", ""]
        for name, blurb in docs:
            title, sections = headings(strip_nav((DOCS / name).read_text()))
            out.append(f"- **[{title}]({name})**: {blurb}.")
            out += [f"  - [{s}]({name}#{a})" for s, a in sections]
        out.append("")
    out += ["## Release", ""]
    for text, name, heading in RELEASE:
        out.append(f"- [{text}]({name}#{anchor(heading, {})})")
    out.append("")
    out += [("Contributor rules are in [CONTRIBUTING.md](../CONTRIBUTING.md) and [CLAUDE.md](../CLAUDE.md); "
            "changes by release in the [changelog](../CHANGELOG.md). "
            "This page is generated by `tools/docs_index.py`."), "",
            "## See also", "",
            "- [beets-pysacd](https://github.com/aclater/beets-pysacd): import SACD images into a beets library",
            "- [sacdfs](https://github.com/aclater/sacdfs): SACD images as DSF files in a folder",
            "- [scarletbook-rs](https://github.com/aclater/scarletbook-rs): the SACD engine pysacd uses", "",
            FOOTER]
    return "\n".join(out) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    listed = {name for _, docs in GROUPS for name, _ in docs}
    # docs/assets/ holds the icon files and their README, not documentation pages
    present = {p.relative_to(DOCS).as_posix() for p in DOCS.rglob("*.md")
               if p.relative_to(DOCS).parts[0] != "assets"} - {"README.md"}
    problems = [f"docs/{n} is not in tools/docs_index.py GROUPS" for n in sorted(present - listed)]
    problems += [f"docs/{n} is listed but missing" for n in sorted(listed - present)]
    for _, name, heading in RELEASE:
        found = re.findall(r"^#{2,3} (.+?)\s*$", strip_nav((DOCS / name).read_text()), re.MULTILINE)
        if heading not in found:
            problems.append(f"docs/{name} has no heading {heading!r} (tools/docs_index.py RELEASE)")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    wanted = {DOCS / "README.md": index()}
    wanted |= {DOCS / n: with_nav((DOCS / n).read_text(), n) for n in sorted(listed)}
    stale = [p for p, text in wanted.items() if not p.exists() or p.read_text() != text]
    if check:
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date: run python3 tools/docs_index.py", file=sys.stderr)
        return 1 if stale else 0
    for p in stale:
        p.write_text(wanted[p])
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
