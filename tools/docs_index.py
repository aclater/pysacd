#!/usr/bin/env python3
"""Generate docs/README.md (the documentation index) and each document's navigation header.

    python3 tools/docs_index.py           # rewrite the index and the headers
    python3 tools/docs_index.py --check   # exit 1 if anything is out of date (run by the tests)

The index lists every document with links to its sections. Each document starts with a
breadcrumb back to the README and the index and, when it has three or more sections, a
contents line. Both are generated from the headings, so they can't drift.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"

# Reading order. A document missing from here fails the check, so new docs get placed.
GROUPS: list[tuple[str, list[tuple[str, str]]]] = [
    ("Using pysacd", [
        ("quickstart.md", "install, and a tour of the commands"),
        ("sacd_extract.md", "migrating from sacd_extract, compatibility policy, verification"),
        ("converting.md", "naming templates, tags, MusicBrainz, gapless PCM"),
        ("library.md", "the Python API, what's parsed, image formats"),
        ("ps3-protocol.md", "reading from a PS3: usage, the wire protocol and the PS3's quirks"),
        ("logging.md", "what to attach when something fails"),
    ]),
    ("Background", [
        ("performance.md", "benchmarks and their conditions"),
        ("security.md", "hostile discs, servers and text"),
        ("clean-room.md", "where the code came from, licences, acknowledgements"),
        ("dst-bitstream.md", "the clean-room DST specification"),
    ]),
    ("Contributing", [
        ("development.md", "building, tests, CI, testing without a PS3"),
    ]),
]

NAV_START, NAV_END = "<!-- nav: generated by tools/docs_index.py -->", "<!-- /nav -->"
MIN_SECTIONS = 3


def anchor(heading: str, seen: dict[str, int]) -> str:
    """GitHub's heading anchor: lower case, punctuation dropped, spaces to hyphens, -N for repeats."""
    text = re.sub(r"`|\*\*|\[([^\]]*)\]\([^)]*\)", r"\1", heading).strip().lower()
    slug = re.sub(r"[^\w\- ]", "", text).replace(" ", "-")
    n = seen.get(slug, 0)
    seen[slug] = n + 1
    return slug if n == 0 else f"{slug}-{n}"


def headings(text: str) -> tuple[str, list[tuple[str, str]]]:
    """The document's title and its level-2 sections as (text, anchor); fenced code is skipped."""
    title, fenced = "", False
    sections: list[tuple[str, str]] = []
    seen: dict[str, int] = {}
    for line in text.splitlines():
        if line.startswith("```"):
            fenced = not fenced
            continue
        m = None if fenced else re.match(r"(#{1,6}) (.+?)\s*$", line)
        if not m:
            continue
        a = anchor(m[2], seen)
        if len(m[1]) == 1 and not title:
            title = m[2]
        elif len(m[1]) == 2:
            sections.append((m[2], a))
    return title, sections


def strip_nav(text: str) -> str:
    return re.sub(rf"\A{re.escape(NAV_START)}.*?{re.escape(NAV_END)}\n\n", "", text, flags=re.DOTALL)


def with_nav(text: str) -> str:
    body = strip_nav(text)
    title, sections = headings(body)
    lines = [NAV_START, f"[pysacd](../README.md) › [Documentation](README.md) › {title}"]
    if len(sections) >= MIN_SECTIONS:
        lines += ["", "**Contents:** " + " · ".join(f"[{s}](#{a})" for s, a in sections)]
    return "\n".join(lines + [NAV_END, "", body])


def index() -> str:
    out = ["# pysacd documentation", "",
           "Start with the [README](../README.md) for what pysacd is. Then:", ""]
    for group, docs in GROUPS:
        out += [f"## {group}", ""]
        for name, blurb in docs:
            title, sections = headings(strip_nav((DOCS / name).read_text()))
            out.append(f"- **[{title}]({name})**: {blurb}.")
            out += [f"  - [{s}]({name}#{a})" for s, a in sections]
        out.append("")
    out.append("Contributor rules are in [CLAUDE.md](../CLAUDE.md). "
               "This page is generated by `tools/docs_index.py`.")
    return "\n".join(out) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    listed = {name for _, docs in GROUPS for name, _ in docs}
    present = {p.name for p in DOCS.glob("*.md")} - {"README.md"}
    problems = [f"docs/{n} is not in tools/docs_index.py GROUPS" for n in sorted(present - listed)]
    problems += [f"docs/{n} is listed but missing" for n in sorted(listed - present)]
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    wanted = {DOCS / "README.md": index()}
    wanted |= {DOCS / n: with_nav((DOCS / n).read_text()) for n in sorted(listed)}
    stale = [p for p, text in wanted.items() if not p.exists() or p.read_text() != text]
    if check:
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date: run python3 tools/docs_index.py", file=sys.stderr)
        return 1 if stale else 0
    for p in stale:
        p.write_text(wanted[p])
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
