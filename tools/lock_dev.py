#!/usr/bin/env python3
"""Write requirements-test.txt and requirements-dev.txt: CI's Python dependencies, pinned with
every file's sha256 (#14).

requirements-test.txt is what the test suite needs (the Windows and fuzz jobs); requirements-dev.txt
adds the linters and the build backend. CI installs them with `pip install --require-hashes`, so a
replaced or
tampered release on PyPI fails the install instead of running in CI. The pins below are the
whole dependency closure for Python 3.11-3.14 on Linux, macOS and Windows (check it with
`pip install --dry-run --ignore-installed --report`). Each pinned release must be at least
two weeks old (CLAUDE.md). To update: edit PINS, run `python3 -I tools/lock_dev.py`, commit.
"""

from __future__ import annotations

import datetime
import json
import sys
import urllib.request
from pathlib import Path

# name, version, environment marker ("" = always), group: "test" (the test suite needs it)
# or "dev" (linters and the build backend)
PINS = [
    ("mutagen", "1.48.1", "", "test"),
    ("numpy", "2.4.6", 'python_version < "3.12"', "test"),
    ("numpy", "2.5.4", 'python_version >= "3.12"', "test"),
    ("pytest", "9.1.1", "", "test"),
    ("iniconfig", "2.3.1", "", "test"),
    ("packaging", "26.3", "", "test"),
    ("pluggy", "1.6.0", "", "test"),
    ("pygments", "2.21.0", "", "test"),
    ("colorama", "0.4.6", 'sys_platform == "win32"', "test"),
    ("ruff", "0.17.0", "", "dev"),
    ("mypy", "2.4.0", "", "dev"),
    ("ast-serialize", "0.13.0", "", "dev"),
    ("librt", "0.16.0", "", "dev"),
    ("mypy-extensions", "1.1.0", "", "dev"),
    ("pathspec", "1.1.1", "", "dev"),
    ("typing-extensions", "4.16.0", "", "dev"),
    ("setuptools", "84.0.0", "", "dev"),     # build backend: CI installs pysacd with --no-build-isolation
]
MIN_AGE = datetime.timedelta(days=14)
ROOT = Path(__file__).resolve().parent.parent
OUTPUTS = {"requirements-test.txt": {"test"}, "requirements-dev.txt": {"test", "dev"}}


def main() -> int:
    now = datetime.datetime.now(datetime.UTC)
    blocks: dict[str, list[str]] = {g: [] for g in ("test", "dev")}
    young = []
    for name, version, marker, group in PINS:
        with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as r:
            files = json.load(r)["urls"]
        if not files:
            sys.exit(f"{name} {version}: no files on PyPI")
        uploaded = min(datetime.datetime.fromisoformat(f["upload_time_iso_8601"]) for f in files)
        if now - uploaded < MIN_AGE:
            young.append(f"{name} {version} ({(now - uploaded).days} days old)")
        spec = f"{name}=={version}" + (f" ; {marker}" if marker else "")
        hashes = sorted({f["digests"]["sha256"] for f in files})
        blocks[group].append(spec + " \\")
        blocks[group] += [f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "")
                          for i, h in enumerate(hashes)]
    if young:
        sys.exit("younger than two weeks: " + ", ".join(young))
    for fname, groups in OUTPUTS.items():
        lines = ["# Generated by tools/lock_dev.py; edit PINS there, not this file.",
                 f"# pip install --require-hashes -r {fname}"]
        for g in ("test", "dev"):
            if g in groups:
                lines += blocks[g]
        (ROOT / fname).write_text("\n".join(lines) + "\n")
        print(f"wrote {fname}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
